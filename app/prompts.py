from __future__ import annotations

SUMMARY_PLACEHOLDER = "<<<ВСТАВЬ СЮДА КОНСПЕКТ ИЗ СТАРОЙ СЕССИИ>>>"


def compaction_prompt(session_name: str, used: int, limit: int, date: str) -> str:
    used_txt = f"{max(0, int(used)):,}".replace(",", " ")
    limit_txt = f"{max(0, int(limit)):,}".replace(",", " ")
    return f"""Мы подходим к лимиту контекста в этой сессии (~{used_txt} из {limit_txt} токенов, {date}). Мне нужно перенести работу в новую сессию без потери контекста.

Твоя задача — выдать конспект всего диалога выше. Формат ответа обязателен: приложение автоматически вырезает текст между маркерами и передаёт его в новую сессию. Если маркеров нет или они написаны иначе — перенос не сработает.

Образец, строго по нему:
===КОНСПЕКТ===
(сюда — конспект)
===КОНЕЦ===

Требования к формату — проверь каждое перед отправкой:
1. Первая строка ответа — ровно ===КОНСПЕКТ===: три знака «=», слово КОНСПЕКТ заглавными буквами, ещё три знака «=». Без пробелов внутри, без звёздочек, кавычек и любого форматирования.
2. Последняя строка ответа — ровно ===КОНЕЦ===, так же без пробелов и форматирования.
3. Между маркерами — только сам конспект, готовый текст первого сообщения для новой сессии: без обращений ко мне и без вступлений вроде «вот конспект».
4. Никаких других строк с «===», кроме этих двух маркеров. Не переводи маркеры, не меняй регистр, не заменяй «=» дефисами или тире.
5. Весь ответ — это только блок от ===КОНСПЕКТ=== до ===КОНЕЦ===. Ничего до первого маркера и ничего после второго.
6. Если не хватает места — сокращай содержание, но маркеры обязаны остаться. Лучше короткий конспект с маркерами, чем подробный без них.

Содержание конспекта:
   • Задача и цель — что мы делаем и зачем.
   • Исходные данные и ограничения: стек, версии, железо, бюджет, сроки.
   • Что уже сделано — по шагам, с ключевыми решениями и причинами.
   • Рабочие детали, которые нельзя потерять: имена файлов и путей, команды, конфиги, API, формулы, тексты, ссылки.
   • Текущее состояние: что работает, что сломано, где именно остановились.
   • Открытые вопросы, риски и тупиковые варианты — чтобы не повторять их.
   • Следующие шаги — нумерованный список, начиная с ближайшего.
   • Мои предпочтения по стилю ответов: язык, формат, степень подробности.

Правила содержания: ничего не выдумывай; если чего-то не знаешь — пометь «не выяснено». Пиши тезисно, без воды. Не задавай вопросов.

Начинай ответ сразу с ===КОНСПЕКТ=== и не пиши ничего до него."""


def resume_prompt(session_name: str, date: str) -> str:
    return f"""Продолжаем работу, начатую в другой сессии. Ниже — конспект предыдущей сессии (она упёрлась в лимит контекста, {date}).

{SUMMARY_PLACEHOLDER}

Как работаем:
• Не пересказывай конспект и не оценивай его — просто прими как контекст.
• Не задавай уточняющих вопросов, если ответ выводится из конспекта.
• Начни с короткого плана (3–6 пунктов) и сразу переходи к первому пункту.
• Если не хватает действительно критичной информации — задай один короткий вопрос и остановись.
• Сохраняй прежние договорённости, стиль и уровень детализации."""


def short_transfer_hint(session_name: str) -> str:
    return (
        f"Сессия «{session_name}»: скопируй промт сжатия, отправь его в старую сессию, "
        "затем открой новую сессию и вставь туда конспект вместе с промтом продолжения."
    )
